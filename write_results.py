#!/usr/bin/env python3
"""Write the measured-results section of docs/BOUNDARY.md from a run report.

Numbers in prose drift. Every count in this project that was typed by hand has
drifted at least once - README task counts, the coverage matrix, the evidence
table - so the one section that will be quoted most is generated from the report
it describes and replaced wholesale on each run.

    python3 write_results.py research/deepseek_full.json [more_shards.json ...]
"""

import collections
import json
import pathlib
import sys

import analyse_run

DOC = pathlib.Path(__file__).resolve().parent / "docs" / "BOUNDARY.md"
START = "<!-- results:start -->"
END = "<!-- results:end -->"


def section(run):
    tasks = run["tasks"]
    scored = [t for t in tasks if t.get("outcome") in ("resolved", "agent", "capped")]
    passed = [t for t in scored if t.get("passed")]
    excluded = len(tasks) - len(scored)
    pf = 100.0 * len(passed) / max(1, len(scored))
    pc = 100.0 * sum(t.get("score") or 0 for t in scored) / max(1, len(scored))

    native = run.get("policy") in ("deepseek", "openai", "model")
    L = [START, "",
         "## Measured: %s%s" % (run.get("model") or run.get("policy"),
                                ", native tool calling" if native else " (scripted policy)"),
         "",
         "_Generated by `write_results.py` from the run report; do not edit by hand._",
         "",
         "| | |",
         "|---|---|",
         "| world | `%s` |" % run.get("world_id", "?"),
         "| episodes | %d (%d attributable, %d excluded as harness/environment) |"
         % (len(tasks), len(scored), excluded),
         "| **Horizon-SWE-PF** | **%.1f%%** (%d/%d) |" % (pf, len(passed), len(scored)),
         "| **Horizon-SWE-PC** | **%.1f** |" % pc,
         ""]

    # Budget exhaustion is our constraint, not the model's ceiling. It is counted
    # as a failure - a run that never finishes did not do the task - but burying
    # it would overstate how much of the gap is capability.
    capped = sum(1 for t in scored if t.get("outcome") == "capped")
    if capped:
        without = [t for t in scored if t.get("outcome") != "capped"]
        pf_wo = 100.0 * sum(1 for t in without if t.get("passed")) / max(1, len(without))
        L += ["%d episode(s) exhausted the %s-turn budget and are counted as failures. "
              "Excluding them the pass rate is %.1f%% (%d/%d) — the difference is the "
              "part of the gap that is our turn limit rather than the model's ceiling."
              % (capped, run.get("max_turns", "turn"), pf_wo,
                 sum(1 for t in without if t.get("passed")), len(without)),
              ""]

    # --- the finding: which dimension breaks -------------------------------
    corr_perfect = sum(1 for t in scored
                       if (t.get("dimension_fractions") or {}).get("correctness", 0) == 1.0)
    depl_broken = sum(1 for t in scored
                      if (t.get("dimension_fractions") or {}).get("deployment", 1) < 1.0)
    corr_pct = 100.0 * corr_perfect / max(1, len(scored))
    lead = ("Correctness is perfect in **%d of %d** attributable episodes (%.0f%%), while "
            "deployment is imperfect in **%d**."
            % (corr_perfect, len(scored), corr_pct, depl_broken))
    # Only claim the finding the numbers actually support.
    if depl_broken and corr_pct >= 60:
        lead += (" The model largely works out what to change and then does not follow the "
                 "procedure for changing it — and that procedure is not in the prompt, it "
                 "is in the knowledge base.")
    elif depl_broken:
        lead += (" Failures are spread across both getting the change right and getting it "
                 "there correctly, rather than concentrated in either.")
    else:
        lead += (" Nothing failed on deployment, so what remains is whether the change "
                 "itself was right.")
    L += ["### Where it breaks", "", lead, ""]

    # Validity first: a difficulty number means nothing if the world was breaking.
    if excluded == 0:
        L += ["Every episode was attributable. **No episode failed with a world-side "
              "symptom** — no missing table, no traceback, no crashed verifier, no "
              "invented tool, no provider outage — so none of the failures below are "
              "ours.", ""]
    else:
        L += ["**%d episode(s) were excluded as harness or environment faults** and are "
              "not in the pass rate. Any non-zero count here weakens every number in "
              "this section until it is explained." % excluded, ""]

    checks = collections.Counter()
    for t in scored:
        if t.get("passed"):
            continue
        for a in t.get("failed_checks") or []:
            checks["%s/%s" % (a["dimension"], a["name"])] += 1
    if checks:
        L += ["| failed check | episodes |", "|---|---|"]
        for name, n in checks.most_common(12):
            L.append("| `%s` | %d |" % (name, n))
        L.append("")

    # --- by category --------------------------------------------------------
    by_cat = collections.defaultdict(list)
    for t in scored:
        by_cat[t.get("category")].append(bool(t.get("passed")))
    L += ["### PF by category", "",
          "The boundary is where this crosses: the families a model clears and the "
          "families it cannot are different questions, and a single average hides both.",
          "", "| category | PF | |", "|---|---|---|"]
    for cat, res in sorted(by_cat.items(), key=lambda kv: -sum(kv[1]) / len(kv[1])):
        p = 100.0 * sum(res) / len(res)
        L.append("| %s | %.0f%% | %d/%d |" % (cat, p, sum(res), len(res)))
    L.append("")

    by_diff = collections.defaultdict(list)
    for t in scored:
        by_diff[t.get("difficulty")].append(bool(t.get("passed")))
    order = [d for d in ("easy", "medium", "hard", "expert") if d in by_diff]
    if order:
        L += ["### PF by difficulty", "", "| difficulty | PF | |", "|---|---|---|"]
        for d in order:
            r = by_diff[d]
            L.append("| %s | %.0f%% | %d/%d |" % (d, 100.0 * sum(r) / len(r), sum(r), len(r)))
        mono = all(100.0 * sum(by_diff[a]) / len(by_diff[a])
                   >= 100.0 * sum(by_diff[b]) / len(by_diff[b])
                   for a, b in zip(order, order[1:]))
        L += ["",
              "PF falls monotonically with the difficulty label."
              if mono else
              "**PF does not fall monotonically with the difficulty label**, so the labels "
              "are describing something other than what this model finds hard. That is a "
              "fact about our labelling, not about the model.",
              ""]

    calls = [t.get("tool_calls", 0) for t in scored]
    if calls:
        won = [t.get("tool_calls", 0) for t in passed] or [0]
        lost = [t.get("tool_calls", 0) for t in scored if not t.get("passed")] or [0]
        L += ["### Effort", "",
              "Mean %.1f tool calls per episode: %.1f when it passed, %.1f when it failed."
              % (sum(calls) / len(calls), sum(won) / len(won), sum(lost) / len(lost)),
              ""]
    L.append(END)
    return "\n".join(L)


def main(paths):
    run = analyse_run.load(paths)
    body = section(run)
    doc = DOC.read_text()
    if START in doc and END in doc:
        head, rest = doc.split(START, 1)
        _, tail = rest.split(END, 1)
        doc = head + body + tail
    else:
        anchor = "## What would count as proof"
        doc = doc.replace(anchor, body + "\n\n" + anchor, 1)
    DOC.write_text(doc)
    print("wrote %d lines into %s" % (len(body.splitlines()), DOC))
    return 0


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a.endswith(".json")]
    sys.exit(main(args or ["research/deepseek_full.json"]))
