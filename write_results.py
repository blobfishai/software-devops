#!/usr/bin/env python3
"""Write the measured-results section of docs/BOUNDARY.md from a run report.

Numbers in prose drift. Every count in this project that was typed by hand has
drifted at least once - README task counts, the coverage matrix, the evidence
table - so the one section that will be quoted most is generated from the report
it describes and replaced wholesale on each run.

    python3 write_results.py research/deepseek_full.json [more_shards.json ...]
"""

import collections
import json
import pathlib
import sys

import analyse_run

DOC = pathlib.Path(__file__).resolve().parent / "docs" / "BOUNDARY.md"
START = "<!-- results:start -->"
END = "<!-- results:end -->"


def section(run):
    tasks = run["tasks"]
    scored = [t for t in tasks if t.get("outcome") in ("resolved", "agent", "capped")]
    passed = [t for t in scored if t.get("passed")]
    excluded = len(tasks) - len(scored)
    pf = 100.0 * len(passed) / max(1, len(scored))
    pc = 100.0 * sum(t.get("score") or 0 for t in scored) / max(1, len(scored))

    native = run.get("policy") in ("deepseek", "openai", "model")
    L = [START, "",
         "## Measured: %s%s" % (run.get("model") or run.get("policy"),
                                ", native tool calling" if native else " (scripted policy)"),
         "",
         "_Generated by `write_results.py` from the run report; do not edit by hand._",
         "",
         "| | |",
         "|---|---|",
         "| world | `%s` |" % run.get("world_id", "?"),
         "| episodes | %d (%d attributable, %d excluded as harness/environment) |"
         % (len(tasks), len(scored), excluded),
         "| **Horizon-SWE-PF** | **%.1f%%** (%d/%d) |" % (pf, len(passed), len(scored)),
         "| **Horizon-SWE-PC** | **%.1f** |" % pc,
         ""]

    # Budget exhaustion is our constraint, not the model's ceiling. It is counted
    # as a failure - a run that never finishes did not do the task - but burying
    # it would overstate how much of the gap is capability.
    capped = sum(1 for t in scored if t.get("outcome") == "capped")
    if capped:
        without = [t for t in scored if t.get("outcome") != "capped"]
        pf_wo = 100.0 * sum(1 for t in without if t.get("passed")) / max(1, len(without))
        L += ["%d episode(s) exhausted the %s-turn budget and are counted as failures. "
              "Excluding them the pass rate is %.1f%% (%d/%d) — the difference is the "
              "part of the gap that is our turn limit rather than the model's ceiling."
              % (capped, run.get("max_turns", "turn"), pf_wo,
                 sum(1 for t in without if t.get("passed")), len(without)),
              ""]

    # --- the finding: which dimension breaks -------------------------------
    corr_perfect = sum(1 for t in scored
                       if (t.get("dimension_fractions") or {}).get("correctness", 0) == 1.0)
    depl_broken = sum(1 for t in scored
                      if (t.get("dimension_fractions") or {}).get("deployment", 1) < 1.0)
    corr_pct = 100.0 * corr_perfect / max(1, len(scored))
    lead = ("Correctness is perfect in **%d of %d** attributable episodes (%.0f%%), while "
            "deployment is imperfect in **%d**."
            % (corr_perfect, len(scored), corr_pct, depl_broken))
    # Only claim the finding the numbers actually support.
    if depl_broken and corr_pct >= 60:
        lead += (" The model largely works out what to change and then does not follow the "
                 "procedure for changing it — and that procedure is not in the prompt, it "
                 "is in the knowledge base.")
    elif depl_broken:
        lead += (" Failures are spread across both getting the change right and getting it "
                 "there correctly, rather than concentrated in either.")
    else:
        lead += (" Nothing failed on deployment, so what remains is whether the change "
                 "itself was right.")
    L += ["### Where it breaks", "", lead, ""]

    # Validity first: a difficulty number means nothing if the world was breaking.
    if excluded == 0:
        L += ["Every episode was attributable. **No episode failed with a world-side "
              "symptom** — no missing table, no traceback, no crashed verifier, no "
              "invented tool, no provider outage — so none of the failures below are "
              "ours.", ""]
    else:
        L += ["**%d episode(s) were excluded as harness or environment faults** and are "
              "not in the pass rate. Any non-zero count here weakens every number in "
              "this section until it is explained." % excluded, ""]

    checks = collections.Counter()
    for t in scored:
        if t.get("passed"):
            continue
        for a in t.get("failed_checks") or []:
            checks["%s/%s" % (a["dimension"], a["name"])] += 1
    if checks:
        L += ["| failed check | episodes |", "|---|---|"]
        for name, n in checks.most_common(12):
            L.append("| `%s` | %d |" % (name, n))
        L.append("")

    # --- by category --------------------------------------------------------
    by_cat = collections.defaultdict(list)
    for t in scored:
        by_cat[t.get("category")].append(bool(t.get("passed")))
    L += ["### PF by category", "",
          "The boundary is where this crosses: the families a model clears and the "
          "families it cannot are different questions, and a single average hides both.",
          "", "| category | PF | |", "|---|---|---|"]
    for cat, res in sorted(by_cat.items(), key=lambda kv: -sum(kv[1]) / len(kv[1])):
        p = 100.0 * sum(res) / len(res)
        L.append("| %s | %.0f%% | %d/%d |" % (cat, p, sum(res), len(res)))
    L.append("")

    by_diff = collections.defaultdict(list)
    for t in scored:
        by_diff[t.get("difficulty")].append(bool(t.get("passed")))
    order = [d for d in ("easy", "medium", "hard", "expert") if d in by_diff]
    if order:
        L += ["### PF by difficulty", "", "| difficulty | PF | |", "|---|---|---|"]
        for d in order:
            r = by_diff[d]
            L.append("| %s | %.0f%% | %d/%d |" % (d, 100.0 * sum(r) / len(r), sum(r), len(r)))
        mono = all(100.0 * sum(by_diff[a]) / len(by_diff[a])
                   >= 100.0 * sum(by_diff[b]) / len(by_diff[b])
                   for a, b in zip(order, order[1:]))
        L += ["",
              "PF falls monotonically with the difficulty label."
              if mono else
              "**PF does not fall monotonically with the difficulty label**, so the labels "
              "are describing something other than what this model finds hard. That is a "
              "fact about our labelling, not about the model.",
              ""]

    calls = [t.get("tool_calls", 0) for t in scored]
    if calls:
        won = [t.get("tool_calls", 0) for t in passed] or [0]
        lost = [t.get("tool_calls", 0) for t in scored if not t.get("passed")] or [0]
        L += ["### Effort", "",
              "Mean %.1f tool calls per episode: %.1f when it passed, %.1f when it failed."
              % (sum(calls) / len(calls), sum(won) / len(won), sum(lost) / len(lost)),
              ""]
    sp = run.get("spend") or {}
    if sp.get("prompt_tokens"):
        L += ["### Cost", "",
              "%.1fM prompt tokens and %.0fK completion tokens over %d episodes — most of "
              "the prompt is the 84 tool schemas, which are identical every turn and so "
              "are almost entirely cache hits."
              % (sp["prompt_tokens"] / 1e6, sp["completion_tokens"] / 1e3,
                 sp.get("episodes", len(scored))),
              ""]
    L.append(END)
    return "\n".join(L)


def ladder_section(run, guided_path, flaky_ids=()):
    """The guidance axis: does stating the procedure change the score?

    If it does not move, the world is testing instruction-following rather than
    judgement. If it moves a great deal, the tasks are mostly a memory test for
    the procedure. The interesting case is in between.
    """
    g = json.loads(pathlib.Path(guided_path).read_text())
    gs = [t for t in g["tasks"] if t.get("outcome") in ("resolved", "agent", "capped")]
    if not gs:
        return ""
    cats = {t.get("category") for t in gs}
    ss = [t for t in run["tasks"]
          if t.get("outcome") in ("resolved", "agent", "capped") and t.get("category") in cats]
    if not ss:
        return ""
    gp, sp = sum(1 for t in gs if t["passed"]), sum(1 for t in ss if t["passed"])
    gpf, spf = 100.0 * gp / len(gs), 100.0 * sp / len(ss)
    was = {t["task_id"]: t["passed"] for t in ss}
    flips = [t["task_id"] for t in gs
             if t["task_id"] in was and was[t["task_id"]] != t["passed"]]

    L = ["", "### The guidance ladder", "",
         "Every task carries two prompts: `instruction` states the outcome, "
         "`instruction_guided` also states the procedure. Same tasks, same model, "
         "measured both ways across %s." % ", ".join(sorted(cats)), "",
         "| prompt | PF | PC |", "|---|---|---|",
         "| outcome only | %.1f%% (%d/%d) | %.1f |"
         % (spf, sp, len(ss), 100.0 * sum(t.get("score") or 0 for t in ss) / len(ss)),
         "| procedure stated | %.1f%% (%d/%d) | %.1f |"
         % (gpf, gp, len(gs), 100.0 * sum(t.get("score") or 0 for t in gs) / len(gs)),
         "| **delta** | **%+.1f points** | |" % (gpf - spf), ""]
    if flips:
        noisy = [f for f in flips if f in set(flaky_ids)]
        L += ["%d task(s) changed side: %s."
              % (len(flips), ", ".join("`%s`" % f for f in flips)), ""]
        caveat = ("On %d tasks a %+.1f-point move is %d task(s) flipping, which is "
                  "suggestive rather than conclusive" % (len(ss), gpf - spf, len(flips)))
        if noisy:
            caveat += (", and %s is independently known to be FLAKY, so at least one "
                       "flip may be variance rather than the prompt"
                       % ", ".join("`%s`" % f for f in noisy))
        L += [caveat + ".", ""]
    L += ["Read plainly: stating the procedure helps, so procedural knowledge is part "
          "of what these tasks demand — but it does not carry the model over the line, "
          "so the rest is judgement about evidence rather than recall of steps.", ""]
    return "\n".join(L)


def band_section(cal_reports):
    """The FLAKY band, from calibration reports.

    A single attempt says pass or fail. Only repeats can say "sometimes", and
    "sometimes" is the only direct evidence that a task sits at the edge of what a
    model can do rather than comfortably above or below it.
    """
    buckets, rows = collections.Counter(), []
    model = attempts = None
    for path in cal_reports:
        r = json.loads(pathlib.Path(path).read_text())
        model = model or r.get("model")
        attempts = attempts or r.get("attempts")
        for t in r.get("tasks", []):
            buckets[t["bucket"]] += 1
            rows.append((t["bucket"], t["task_id"], t["passes"], t["attempts"],
                         t.get("mean_score")))
    if not rows:
        return ""
    order = {"FLAKY": 0, "TOO_HARD": 1, "TOO_EASY": 2, "BUDGET_CAPPED": 3, "TASK_FAULT": 4}
    rows.sort(key=lambda r: (order.get(r[0], 9), -r[2]))
    L = ["", "### Reliability: the FLAKY band", "",
         "Boundary candidates re-run %s times each against %s, with `--all-attempts` so "
         "a first-try pass does not end the probe." % (attempts, model), "",
         "| task | bucket | passes | mean PC |", "|---|---|---|---|"]
    for bucket, tid, passes, n, pc in rows:
        L.append("| `%s` | **%s** | %d/%d | %.2f |" % (tid, bucket, passes, n, pc or 0))
    # tau-bench reliability: the chance ALL k independent attempts succeed. A single
    # pass rate cannot express "sometimes", and sometimes is what these tasks do.
    import math

    def phk(c, n, k):
        return math.comb(c, k) / math.comb(n, k) if k <= n else None

    ks = sorted({r[3] for r in rows})
    series = []
    if ks and max(ks) > 1:
        L += ["", "| k | pass^k |", "|---|---|"]
        for k in range(1, max(ks) + 1):
            vals = [v for v in (phk(r[2], r[3], k) for r in rows) if v is not None]
            if vals:
                series.append(sum(vals) / len(vals))
                L.append("| %d | %.3f |" % (k, series[-1]))
        L.append("")
        if series and series[-1] == 0.0 and series[0] > 0:
            L += ["A %.0f%% single-attempt rate is **%.0f%% when consistency is "
                  "required**: not one boundary task passed all %d attempts. That is "
                  "the whole argument for the metric — a pass rate averages away the "
                  "difference between a model that can do something and a model that "
                  "can do it reliably, and on the tasks that sit at the edge those are "
                  "not the same claim."
                  % (100 * series[0], 100 * series[-1], max(ks)), ""]
        elif series:
            L += ["pass^k falls from %.3f to %.3f across k, so reliability degrades with "
                  "repetition rather than the score being a stable property of the task."
                  % (series[0], series[-1]), ""]

    flaky = buckets.get("FLAKY", 0)
    L += ["",
          "**%d of %d candidates are FLAKY** — the same model, the same task, the same "
          "prompt, passing on some attempts and failing on others. That band is the "
          "point: a task nobody can pass measures nothing, a task everybody passes "
          "measures nothing, and a task that goes both ways is measuring exactly where "
          "capability runs out." % (flaky, len(rows))
          if flaky else
          "**No candidate came back FLAKY.** Every one landed on the same side of the "
          "line all three times, so this probe found no evidence that the world is "
          "measuring at the capability edge for this model.",
          ""]
    if buckets.get("TASK_FAULT"):
        L += ["**%d task(s) failed with world-side symptoms.** Any non-zero count here "
              "invalidates the difficulty reading until fixed." % buckets["TASK_FAULT"], ""]
    return "\n".join(L)


def main(paths, cal_reports=(), guided=None, flaky_ids=()):
    run = analyse_run.load(paths)
    body = section(run)
    if cal_reports:
        body = body.replace(END, band_section(cal_reports) + "\n" + END)
    if guided:
        body = body.replace(END, ladder_section(run, guided, flaky_ids) + "\n" + END)
    doc = DOC.read_text()
    if START in doc and END in doc:
        head, rest = doc.split(START, 1)
        _, tail = rest.split(END, 1)
        doc = head + body + tail
    else:
        anchor = "## What would count as proof"
        doc = doc.replace(anchor, body + "\n\n" + anchor, 1)
    DOC.write_text(doc)
    print("wrote %d lines into %s" % (len(body.splitlines()), DOC))
    return 0


if __name__ == "__main__":
    argv = sys.argv[1:]
    cal = [a for a in argv if "calib" in a or "flaky" in a]
    guided = next((a for a in argv if "guided" in a), None)
    runs = [a for a in argv if a.endswith(".json") and a not in cal and a != guided]
    flaky = []
    for c in cal:
        for t in json.loads(pathlib.Path(c).read_text()).get("tasks", []):
            if t.get("bucket") == "FLAKY":
                flaky.append(t["task_id"])
    sys.exit(main(runs or ["research/deepseek_full.json"], cal, guided, flaky))
